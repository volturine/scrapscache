/** `slot` is an opaque, keyed identifier generated by the client for a logical record.
 * It lets the relay replace an old ciphertext without learning whether it is a note, image, etc. */
export type EncryptedEnvelope = { seq: number; id: string; ciphertext: string; slot: string };
export type OpaqueUpload = Omit<EncryptedEnvelope, 'seq'> & {
	expectedId?: string | null;
	/** The upload continues the version it replaces, which then leaves the history. */
	continues?: boolean;
};
export type OpaqueDelete = { id: string; slot: string };

export type SyncResult = {
	cursor: number;
	envelopes: EncryptedEnvelope[];
	conflicts: EncryptedEnvelope[];
	hasMore: boolean;
	reset: boolean;
	writesAccepted: boolean;
};

export type SyncStoreOptions = {
	maxAccountBytes?: number;
	historyVersions?: number;
};

type AccountRow = {
	nextSeq: number;
	envelopeCount: number;
	ciphertextBytes: number;
};

export type AccountByteQuota = {
	maxBytes: number;
	overridden: boolean;
};

type UsageRow = {
	envelopeCount: number;
	ciphertextBytes: number;
	storageBytes: number;
};

export type SyncQuotas = {
	maxAccountBytes: number;
};

export type OperatorUsage = UsageRow & {
	accounts: number;
	activeByWindowDays: Record<string, number>;
	staleAccounts: number;
};

/** Conservative allowance for row, key, and index storage beyond the ciphertext itself. */
