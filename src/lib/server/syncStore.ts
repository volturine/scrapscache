	// Async so both deployments expose the same shape; see
	// syncStore.contract.test.ts. The Cloudflare store has to await its
	// coordinator before it can hand back a stream.
	async createEventStream(
		accountId: string,
		signal?: AbortSignal,
		clientId?: string
	): Promise<Response> {
		const encoder = new TextEncoder();
		let unsubscribe: (() => void) | undefined;
		let pingInterval: ReturnType<typeof setInterval> | undefined;

		const stream = new ReadableStream({
			start(controller) {
				try {
					controller.enqueue(encoder.encode(': ok\n\n'));
				} catch {
					return;
				}
				unsubscribe = syncEventEmitter.subscribe(accountId, (seq, senderClientId) => {
					if (clientId && senderClientId && clientId === senderClientId) return;
					try {
						controller.enqueue(encoder.encode(`data: ${JSON.stringify({ seq })}\n\n`));
					} catch {
						/* stream closed */
					}
				});
				pingInterval = setInterval(() => {
					try {
						controller.enqueue(encoder.encode(': ping\n\n'));
					} catch {
						/* stream closed */
					}
				}, 25_000);
			},
			cancel() {
				if (pingInterval) clearInterval(pingInterval);
				if (unsubscribe) unsubscribe();
			}
		});

		signal?.addEventListener('abort', () => {
			if (pingInterval) clearInterval(pingInterval);
			if (unsubscribe) unsubscribe();
		});

		return new Response(stream, {
			headers: {
				'Content-Type': 'text/event-stream',
				'Cache-Control': 'no-cache, no-transform',
				Connection: 'keep-alive'
			}
		});
	}
